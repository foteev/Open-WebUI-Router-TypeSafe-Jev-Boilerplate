"""build_pipe.py — assemble single-file Open WebUI Pipe function from sources.

Usage:
    python src/build_pipe.py

Sources:
    src/route.py      → TypeSafe routing logic
    src/pipe_body.py  → Open WebUI Pipe class
    src/agents.json   → Default agent registry
Output:
    dist/router_pipe.py → Paste into Open WebUI Admin → Functions
"""
import ast
import hashlib
import json
from pathlib import Path

SRC = Path(__file__).resolve().parent
OUT = SRC.parent / "dist" / "router_pipe.py"
VERSION = "1.0.0"

FRONTMATTER = f'''"""
title: Universal Assistant Router
author: Open WebUI Community
version: {VERSION}
required_open_webui_version: 0.10.1
description: Universal router pipe powered by TypeSafe Jev. Dispatches user turns to specialist models with automatic clarification and access control.
"""
# GENERATED by src/build_pipe.py from route.py + pipe_body.py + agents.json.
# Source hash: {{hash}}
'''


def main():
    route_src = (SRC / "route.py").read_text(encoding="utf-8")
    body_src = (SRC / "pipe_body.py").read_text(encoding="utf-8")
    agents_src = (SRC / "agents.json").read_text(encoding="utf-8")

    # Validate JSON
    json.loads(agents_src)
    if "'''" in agents_src:
        raise SystemExit("agents.json must not contain triple single quotes")

    # route.py: drop module docstring and __future__ import
    tree = ast.parse(route_src)
    first = tree.body[0]
    lines = route_src.splitlines()
    if isinstance(first, ast.Expr) and isinstance(getattr(first, "value", None), ast.Constant):
        lines = lines[first.end_lineno:]
    route_part = "\n".join(l for l in lines if l.strip() != "from __future__ import annotations").strip()

    # pipe_body.py: drop dev-only imports and embed agents.json
    start = body_src.index("# BUILD-STRIP-START")
    end = body_src.index("# BUILD-STRIP-END")
    body_part = (body_src[:start] + body_src[body_src.index("\n", end) + 1:]).strip()
    body_part = body_part.replace("__AGENTS_JSON__", agents_src.strip())

    digest = hashlib.sha256((route_src + body_src + agents_src).encode()).hexdigest()[:12]
    full_text = (
        FRONTMATTER.replace("{hash}", digest)
        + "from __future__ import annotations\n\n"
        + "# ── Routing Logic (TypeSafe Jev) ──────────────────────────────────────────────\n"
        + route_part
        + "\n\n\n"
        + "# ── Open WebUI Pipe Handler ──────────────────────────────────────────────────\n"
        + body_part
        + "\n"
    )

    # Verify Python syntax
    compile(full_text, str(OUT), "exec")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(full_text, encoding="utf-8")
    print(f"Successfully built {OUT.name} ({len(full_text):,} bytes, hash: {digest})")


if __name__ == "__main__":
    main()
